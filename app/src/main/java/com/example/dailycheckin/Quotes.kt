/** 名言收藏：SharedPreferences + JSON 数组本地存储 */
object FavQuotes {

    private const val PREF = "settings_pref"
    private const val KEY = "fav_quotes"

    fun list(context: Context): MutableList<String> {
        val json = context.applicationContext
            .getSharedPreferences(PREF, Context.MODE_PRIVATE)
            .getString(KEY, "[]") ?: "[]"
        val arr = org.json.JSONArray(json)
        val out = mutableListOf<String>()
        for (i in 0 until arr.length()) out.add(arr.getString(i))
        return out
    }

    private fun save(context: Context, list: List<String>) {
        val arr = org.json.JSONArray()
        list.forEach { arr.put(it) }
        context.applicationContext
            .getSharedPreferences(PREF, Context.MODE_PRIVATE)
            .edit().putString(KEY, arr.toString()).apply()
    }

    /** 收藏一条，已存在返回 false */
    fun add(context: Context, quote: String): Boolean {
        val l = list(context)
        if (l.contains(quote)) return false
        l.add(quote)
        save(context, l)
        return true
    }

    fun remove(context: Context, quote: String) {
        val l = list(context)
        l.remove(quote)
        save(context, l)
    }
}
